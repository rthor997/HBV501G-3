package org.example.klifurapp.service.implementation;

import org.example.klifurapp.exception.ResourceNotFoundException;
import org.example.klifurapp.service.ImageStorageService;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.core.io.Resource;
import org.springframework.core.io.UrlResource;
import org.springframework.http.HttpStatus;
import org.springframework.http.MediaType;
import org.springframework.stereotype.Service;
import org.springframework.web.multipart.MultipartFile;
import org.springframework.web.server.ResponseStatusException;

import javax.imageio.ImageIO;
import java.io.IOException;
import java.io.InputStream;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.UUID;

@Service
public class ImageStorageServiceImplementation implements ImageStorageService {

    private final Path uploadDir;

    public ImageStorageServiceImplementation(
            @Value("${app.images.directory}") String directory
    ) throws IOException {
        this.uploadDir = Paths.get(directory)
                .toAbsolutePath()
                .normalize(); // Tekur basically út . í paths eins og ./file

        Files.createDirectories(uploadDir);
    }

    public String store(MultipartFile file) throws IOException {

        if (file.isEmpty()) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST, "Image is empty"
            );
        }

        if (file.getSize() > 5L * 1024 * 1024) {
            throw new ResponseStatusException(
                    HttpStatus.CONTENT_TOO_LARGE,
                    "Image exceeds 5 MB"
            );
        }

        String contentType = file.getContentType();

        if (!MediaType.IMAGE_JPEG_VALUE.equals(contentType)
                && !MediaType.IMAGE_PNG_VALUE.equals(contentType)) {
            throw new ResponseStatusException(
                    HttpStatus.BAD_REQUEST,
                    "Only JPEG and PNG images are supported"
            );
        }

        // Check that the contents are actually an image
        try (InputStream input = file.getInputStream()) {
            if (ImageIO.read(input) == null) {
                throw new ResponseStatusException(
                        HttpStatus.BAD_REQUEST,
                        "Invalid image contents"
                );
            }
        }

        String extension =
                MediaType.IMAGE_PNG_VALUE.equals(contentType)
                        ? ".png" : ".jpg";

        // Creates a random filename
        String filename = UUID.randomUUID() + extension;

        // Destination Path for file using filename
        Path destination = uploadDir.resolve(filename);

        try (InputStream input = file.getInputStream()) {
            Files.copy(input, destination);
        }

        return filename;
    }

    public Resource load(String filename) throws IOException {

        Path path = resolve(filename);

        // Checks whether the file exists
        if (!Files.isRegularFile(path)) {
            throw new ResourceNotFoundException(
                    "Image not found"
            );
        }

        return new UrlResource(path.toUri());
    }

    public void delete(String filename) throws IOException {
        Files.deleteIfExists(resolve(filename));
    }

    private Path resolve(String filename) {

        // Filenames must be generated by our application.
        if (filename == null ||
                !filename.matches(
                        "[0-9a-fA-F-]{36}\\.(jpg|png)"
                )) {
            throw new IllegalArgumentException(
                    "Invalid image filename"
            );
        }

        Path path = uploadDir.resolve(filename).normalize();

        if (!path.getParent().equals(uploadDir)) {
            throw new IllegalArgumentException(
                    "Invalid image path"
            );
        }

        return path;
    }
}
